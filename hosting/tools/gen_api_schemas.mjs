// Writes hosting/core/api_schemas.js from contracts/api/*.request.schema.json, so the handlers can validate requests without importing JSON
// (a plain module loads in every bundler, like contracts/event_schemas.js). Run: node hosting/tools/gen_api_schemas.mjs
// `--check` only compares and exits 1 on a difference (a test does the same). Only request schemas are bundled; responses are checked in tests.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const API = path.join(here, '..', '..', 'contracts', 'api'), OUT = path.join(here, '..', 'core', 'api_schemas.js');
export const NAMES = ['email_start', 'email_verify', 'email_complete', 'me_profile_put', 'me_delete', 'me_export', 'me_logout_all'];

export function render() {
  const o = {};
  for (const n of NAMES) o[n] = JSON.parse(readFileSync(path.join(API, n + '.request.schema.json'), 'utf8'));
  return `// GENERATED by hosting/tools/gen_api_schemas.mjs from contracts/api/*.request.schema.json. Do not edit by hand: change the contract
// (with the architect and the owner), then run node hosting/tools/gen_api_schemas.mjs. A test fails if this file drifts from the contracts.
const freeze = v => { if (v && typeof v === 'object') { for (const x of Object.values(v)) freeze(x); Object.freeze(v); } return v; };
export const SCHEMAS = freeze(${JSON.stringify(o, null, 1)});
`;
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = render();
  if (process.argv.includes('--check')) { let cur = ''; try { cur = readFileSync(OUT, 'utf8'); } catch { /* missing */ } if (cur !== text) { console.error('hosting/core/api_schemas.js is out of date: run node hosting/tools/gen_api_schemas.mjs'); process.exit(1); } console.log('api_schemas.js is current'); }
  else { writeFileSync(OUT, text); console.log('wrote ' + path.relative(process.cwd(), OUT)); }
}
